"""Write docs/TRACEABILITY.md: feature -> requirements -> acceptance criteria -> tests that name them.

Reads the SPEC files (features from the §3 scope table, REQ/NFR/SEC and AC rows per section) and every test file
in the repo. Re-run after a SPEC or test change:  python3 scripts/traceability.py
"""
import re
import subprocess
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SPECS = ["docs/SPEC.md", "docs/SPEC-auth.md", "docs/SPEC-order-workflow.md", "docs/SPEC-data-upload.md"]
REQ_ROW = re.compile(r"^\| ?\*{0,2}((?:REQ|NFR|SEC)-[A-Z0-9-]*\d+)\*{0,2} ?\|")
AC_ROW = re.compile(r"^\| ?\*{0,2}(AC-[A-Z0-9-]*\d+)\*{0,2} ?\|")
AC_REF = re.compile(r"AC-[A-Z]+(?:-[A-Z]+)*-\d+")
# Python tests also name ACs in the function name: test_ac_diag_04_... -> AC-DIAG-04.
AC_FN = re.compile(r"\bdef test_((?:ac_[a-z]+(?:_[a-z]+)*_\d+_?(?:and_)?)+)")
AC_IN_FN = re.compile(r"ac_([a-z]+(?:_[a-z]+)*)_(\d+)")
SECTION = re.compile(r"^#{2,3} (\d+(?:\.\d+)?)\.? (.*)")
FEATURE_ROW = re.compile(r"^\| ([A-Z]\d+[a-z]?) \| ([^|]+) \| ([^|]+) \| ([^|]+) \| ([^|]+) \|")
TEST_FILE = re.compile(r"(\.test\.(ts|tsx|mjs|js)|\.spec\.ts|(^|/)test_[^/]*\.py)$")


def spec_sections(path):
    """{section: {'title', 'reqs', 'acs'}} for one SPEC file."""
    out = defaultdict(lambda: {"title": "", "reqs": [], "acs": []})
    cur = "0"
    for line in (ROOT / path).read_text().splitlines():
        if m := SECTION.match(line):
            cur = m.group(1)
            out[cur]["title"] = m.group(2).strip()
        elif m := REQ_ROW.match(line):
            out[cur]["reqs"].append(m.group(1))
        elif m := AC_ROW.match(line):
            out[cur]["acs"].append(m.group(1))
    return out


def features():
    """Feature rows of SPEC §3: (id, name, tier, [sections])."""
    rows = []
    for line in (ROOT / "docs/SPEC.md").read_text().splitlines():
        m = FEATURE_ROW.match(line)
        if m and m.group(1) != "ID":
            rows.append((m.group(1), m.group(2).strip(), m.group(4).strip(), re.findall(r"§(\d+(?:\.\d+)?)", m.group(5))))
    return rows


def tests_by_ac():
    files = subprocess.run(["git", "ls-files"], cwd=ROOT, capture_output=True, text=True, check=True).stdout.split()
    named = defaultdict(set)
    for f in files:
        if TEST_FILE.search(f):
            text = (ROOT / f).read_text(errors="ignore")
            acs = set(AC_REF.findall(text))
            for fn in AC_FN.findall(text):
                acs |= {f"AC-{area.upper().replace('_', '-')}-{n}" for area, n in AC_IN_FN.findall(fn)}
            for ac in acs:
                named[ac].add(f)
    return named


def short(path):
    return Path(path).name


def main():
    named = tests_by_ac()
    main_spec = spec_sections("docs/SPEC.md")
    lines = [
        "# Traceability: feature → requirement → acceptance criterion → test",
        "",
        "Generated by `python3 scripts/traceability.py` from the SPEC files and the test files in git. Do not edit by",
        "hand. A requirement's acceptance criterion has the same number (SPEC conventions); an AC counts as tested when",
        "a test file names it.",
        "",
    ]
    total = tested = 0
    summary = []
    for path in SPECS:
        secs = spec_sections(path)
        acs = [a for s in secs.values() for a in s["acs"]]
        t = sum(1 for a in acs if a in named)
        total += len(acs)
        tested += t
        reqs = sum(len(s["reqs"]) for s in secs.values())
        summary.append(f"| `{path}` | {reqs} | {len(acs)} | {t} | {len(acs) - t} |")
    lines += ["## Summary", "", "| SPEC file | Requirements | ACs | ACs named by a test | Not named |", "|---|---|---|---|---|",
              *summary, f"| **Total** | | **{total}** | **{tested}** | **{total - tested}** |", ""]

    # Requirements live per SPEC section, and several features share a section, so the map is section by section.
    by_sec = defaultdict(list)
    for fid, name, tier, secs in features():
        for s in secs:
            by_sec[s].append(f"{fid} {name} ({tier})")
    lines += ["## SPEC §3 features to requirements and tests", "",
              "| SPEC section | Features | Requirements | ACs named by a test / total | Test files |", "|---|---|---|---|---|"]
    for sec in sorted(by_sec, key=lambda s: [int(p) for p in s.split(".")]):
        s = main_spec.get(sec, {"title": "", "reqs": [], "acs": []})
        files = sorted({short(f) for a in s["acs"] for f in named.get(a, ())})
        t = sum(1 for a in s["acs"] if a in named)
        lines.append(f"| §{sec} {s['title']} | {'<br>'.join(by_sec[sec])} | {', '.join(s['reqs']) or '—'} | "
                     f"{t} / {len(s['acs'])} | {', '.join(f'`{f}`' for f in files) or '—'} |")
    lines.append("")

    lines += ["## Acceptance criteria and the tests that name them", ""]
    for path in SPECS:
        lines += [f"### `{path}`", "", "| Section | AC | Tests |", "|---|---|---|"]
        for sec, s in spec_sections(path).items():
            for ac in s["acs"]:
                files = sorted(named.get(ac, ()))
                lines.append(f"| §{sec} {s['title'][:40]} | {ac} | "
                             f"{', '.join(f'`{f}`' for f in files) if files else '**not named by a test**'} |")
        lines.append("")
    (ROOT / "docs/TRACEABILITY.md").write_text("\n".join(lines))
    print(f"docs/TRACEABILITY.md: {total} ACs, {tested} named by a test")


if __name__ == "__main__":
    main()
