"""SD-09 synthetic scale and second-client datasets (SPEC §12.1, SPEC-data-upload AC-DATA-23).

Both are generated FROM the supplied dataset and are synthetic; they never feed the headline figures or the replay.
- write_replica: an N× copy. Copy 0 is the supplied data; copies 1..N-1 get new delivery, order, penalty and complaint
  ids (suffix -Rkk) and keep every other value, so rates stay the same and counts scale by N. Rows are interleaved by
  order time with a seeded shuffle, so the store is not N blocks back to back.
- write_second_client: the same deliveries as another company would hold them: other client, delivery, order,
  penalty and complaint ids, other carrier and warehouse codes, and dates moved to Apr-Sep 2020 (a whole number of
  weeks earlier, so weekdays and calendar months match). A client_profile.json names that company's carriers, lanes
  and backtest split: the only thing a new client needs besides its data.

Columns are read and written as strings, so every value not renamed keeps its exact text (line endings become LF).
"""
import json
from pathlib import Path

import numpy as np
import pandas as pd

SEED = 20261030
FILES = ["deliveries.csv", "clients.csv", "carriers.csv", "warehouses.csv", "warehouse_region_distance_miles.csv",
         "sla_penalties.csv", "complaints.csv", "customer_success_time_study.csv"]
NOTE = ("SYNTHETIC DATA (SD-09). Generated by backend/synthetic-data/generators/sd09_scale.py from "
        "Halcyon-Hackathon-Dataset/. Not Halcyon's data; never use for headline figures or the replay.\n")

# Second client: "Northwind" (synthetic). 2191 days = 313 weeks: 2026-04-01 (Wed) -> 2020-04-01 (Wed).
SECOND_NAME = "Northwind Freight (synthetic)"
SECOND_SHIFT = pd.Timedelta(days=2191)
SECOND_YEAR = 2020
CARRIER_MAP = {"A": "ATLAS", "B": "BOREAL", "C": "CEDAR", "D": "DUNE", "E": "EMBER", "F": "FJORD"}
WAREHOUSE_MAP = {f"W{i}": f"DC{i}" for i in range(1, 6)}
TS_FORMAT, DATE_FORMAT = "%Y-%m-%d %H:%M", "%Y-%m-%d"


def _read(src: Path, name: str) -> pd.DataFrame:
    return pd.read_csv(src / name, dtype=str, keep_default_na=False)


def _write(out: Path, tables: dict[str, pd.DataFrame], manifest: dict) -> None:
    out.mkdir(parents=True, exist_ok=True)
    for name, df in tables.items():
        df.to_csv(out / name, index=False)
    manifest["rows"] = {name: len(df) for name, df in tables.items()}
    (out / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
    (out / "SYNTHETIC.txt").write_text(NOTE)


def _tag(ids: pd.Series, k: int) -> pd.Series:
    return ids if k == 0 else ids + f"-R{k:02d}"


def replicate(src: Path, factor: int, seed: int = SEED) -> dict[str, pd.DataFrame]:
    if factor < 1:
        raise ValueError("factor must be at least 1")
    t = {name: _read(src, name) for name in FILES}
    d, pen, cmp_ = t["deliveries.csv"], t["sla_penalties.csv"], t["complaints.csv"]
    copies = [d.assign(delivery_id=_tag(d.delivery_id, k), order_id=_tag(d.order_id, k)) for k in range(factor)]
    rng = np.random.default_rng(seed)
    big = pd.concat(copies, ignore_index=True)
    big = big.iloc[rng.permutation(len(big))]
    # "YYYY-MM-DD HH:MM" sorts as text; the stable sort keeps the seeded order within the same minute.
    t["deliveries.csv"] = big.sort_values("order_received_ts", kind="stable").reset_index(drop=True)
    t["sla_penalties.csv"] = pd.concat([pen.assign(penalty_id=_tag(pen.penalty_id, k),
                                                   delivery_id=_tag(pen.delivery_id, k)) for k in range(factor)],
                                       ignore_index=True)
    t["complaints.csv"] = pd.concat([cmp_.assign(complaint_id=_tag(cmp_.complaint_id, k),
                                                 delivery_id=_tag(cmp_.delivery_id, k)) for k in range(factor)],
                                    ignore_index=True)
    return t


def write_replica(src: Path, out: Path, factor: int, seed: int = SEED) -> Path:
    _write(out, replicate(src, factor, seed), {
        "synthetic": True, "dataset": "SD-09 scale replica", "source": "Halcyon-Hackathon-Dataset",
        "factor": factor, "seed": seed})
    return out


def _shift(s: pd.Series, fmt: str) -> pd.Series:
    parsed = pd.to_datetime(s.replace("", None), format=fmt)
    return (parsed - SECOND_SHIFT).dt.strftime(fmt).fillna("")


def second_client(src: Path) -> dict[str, pd.DataFrame]:
    t = {name: _read(src, name) for name in FILES}
    client = {c: f"N{1000 + int(c[1:])}" for c in t["clients.csv"].client_id}

    d = t["deliveries.csv"]
    d = d.assign(delivery_id="NW" + d.delivery_id.str[1:], order_id=d.order_id.str.replace("ORD-", "NWO-"),
                 client_id=d.client_id.map(client), carrier_id=d.carrier_id.map(CARRIER_MAP),
                 nearest_warehouse_id=d.nearest_warehouse_id.map(WAREHOUSE_MAP),
                 fulfilment_warehouse_id=d.fulfilment_warehouse_id.map(WAREHOUSE_MAP))
    for col in ["order_received_ts", "shipped_ts"]:
        d[col] = _shift(d[col], TS_FORMAT)
    for col in ["promised_date", "pick_list_date", "delivered_date"]:
        d[col] = _shift(d[col], DATE_FORMAT)
    t["deliveries.csv"] = d

    c = t["clients.csv"]
    t["clients.csv"] = c.assign(client_id=c.client_id.map(client),
                                client_name="Northwind client " + c.client_id.str[1:] + " (synthetic)")
    k = t["carriers.csv"]
    t["carriers.csv"] = k.assign(carrier_id=k.carrier_id.map(CARRIER_MAP),
                                 carrier_name=k.carrier_id.map(CARRIER_MAP).str.title() + " Freight (synthetic)")
    w = t["warehouses.csv"]
    t["warehouses.csv"] = w.assign(warehouse_id=w.warehouse_id.map(WAREHOUSE_MAP),
                                   warehouse_name="Northwind " + w.warehouse_name + " (synthetic)")
    dist = t["warehouse_region_distance_miles.csv"]
    t["warehouse_region_distance_miles.csv"] = dist.assign(warehouse_id=dist.warehouse_id.map(WAREHOUSE_MAP))
    p = t["sla_penalties.csv"]
    t["sla_penalties.csv"] = p.assign(penalty_id=p.penalty_id.str.replace("PEN", "NWP"),
                                      delivery_id="NW" + p.delivery_id.str[1:], client_id=p.client_id.map(client))
    m = t["complaints.csv"]
    t["complaints.csv"] = m.assign(complaint_id=m.complaint_id.str.replace("CMP", "NWC"),
                                   delivery_id="NW" + m.delivery_id.str[1:], client_id=m.client_id.map(client),
                                   complaint_date=_shift(m.complaint_date, DATE_FORMAT))
    s = t["customer_success_time_study.csv"]
    t["customer_success_time_study.csv"] = s.assign(week_of=_shift(s.week_of, DATE_FORMAT))
    return t


def second_client_profile() -> dict:
    """The per-client rules (ROADMAP §4 'rules as configuration'): this client's names for the same lanes."""
    from analytics.carriers import backtest, tracking
    from analytics.core import load
    return {
        "client": SECOND_NAME,
        "synthetic": True,
        "bad_lanes": sorted([CARRIER_MAP[c], region] for c, region in load.BAD_LANES),
        "friday_cap_carrier": CARRIER_MAP[load.FRIDAY_CAP_CARRIER],
        "backtest_split": (backtest.SPLIT - SECOND_SHIFT).strftime(DATE_FORMAT),
        "tracking_feeds": {"api": [CARRIER_MAP[c] for c in tracking.API],
                           "portal": [CARRIER_MAP[c] for c in tracking.PORTAL],
                           "batch": [CARRIER_MAP[c] for c in tracking.BATCH]},
    }


def write_second_client(src: Path, out: Path) -> Path:
    _write(out, second_client(src), {
        "synthetic": True, "dataset": "SD-09 second client", "client": SECOND_NAME,
        "source": "Halcyon-Hackathon-Dataset", "date_shift_days": -SECOND_SHIFT.days,
        "carriers": CARRIER_MAP, "warehouses": WAREHOUSE_MAP, "clients": "C### -> N1###"})
    (out / "client_profile.json").write_text(json.dumps(second_client_profile(), indent=2) + "\n")
    return out

